"""Build final YOLO train/test dataset directories for LOCO and fl_pj.

Reads the deduped labels and the pipeline.db for each job, builds a proper
YOLO dataset layout (images/ + labels/ + classes.txt + data.yaml) at a
destination root. Existing source directories are NOT modified.

fl_pj is split into train + test by video (no video crosses splits), using
the strategy chosen in the dry-run:

  - Eligibility: video has at least one forklift OR palletjack bbox whose
    distance to every image edge is >= buffer (default 0.02).
  - Cap: videos with more than max_test_frames (default 10) are excluded
    from test eligibility entirely, which preserves the no-cross-split
    guarantee (their frames all go to train).
  - Selection: seeded random shuffle of eligible videos, then pick until
    the frame quota (default 10% of all fl_pj frames) is reached.
  - Everything not in test goes to train (including the >10-frame videos
    that were ineligible).

LOCO has no split — all frames go to loco_train.

Images are hardlinked by default (same filesystem -> zero extra disk) with
fallback to copy. labels/*.txt are copied. Revert = rm -rf the target root.

Usage:

  python -m data_miner.auto_annotation_v4.scripts.split_datasets \\
      --dest output/yolo_datasets \\
      --seed 0
"""
from __future__ import annotations

import argparse
import json
import os
import random
import re
import shutil
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


VIDEO_PAT = re.compile(r"^(.*)_(\d+)$")


def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--dest", type=Path, default=Path("output/yolo_datasets"),
        help="Root output directory. Three sub-dirs will be created:"
             " loco_train, flpj_train, flpj_test.",
    )
    p.add_argument("--seed", type=int, default=0,
                   help="RNG seed for the fl_pj test-video pick.")
    p.add_argument("--buffer", type=float, default=0.02,
                   help="Edge margin for 'fully visible' (normalized 0..0.5).")
    p.add_argument("--max-test-frames", type=int, default=10,
                   help="Max frames a test video may contribute. Videos with"
                        " more total frames are ineligible (go to train).")
    p.add_argument("--test-frame-share", type=float, default=0.10,
                   help="Target share of all fl_pj frames in test.")
    p.add_argument("--no-hardlink", action="store_true",
                   help="Always copy images instead of hardlinking.")
    return p.parse_args()


# ---------------------------------------------------------------------------
# IO helpers
# ---------------------------------------------------------------------------


def _link_or_copy(src: Path, dst: Path, hardlink: bool) -> None:
    if dst.exists():
        dst.unlink()
    if hardlink:
        try:
            os.link(src, dst)
            return
        except OSError:
            pass  # fall through to copy (cross-filesystem etc.)
    shutil.copy2(src, dst)


def _write_classes_and_data_yaml(
    dest: Path, classes_path: Path, split_dirs: dict[str, Path]
) -> None:
    """Copy classes.txt and emit a data.yaml (YOLOv5/8-compatible)."""
    dst_classes = dest / "classes.txt"
    shutil.copy2(classes_path, dst_classes)

    # Parse "<id> <name>" classes.txt to build the YOLO `names` map
    names_by_id: dict[int, str] = {}
    for line in dst_classes.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split(" ", 1)
        try:
            cid = int(parts[0])
            cname = parts[1] if len(parts) > 1 else ""
        except ValueError:
            continue
        names_by_id[cid] = cname

    max_id = max(names_by_id) if names_by_id else -1
    # YOLO needs a contiguous list; fill gaps with "_reserved_<id>".
    names_list = [names_by_id.get(i, f"_reserved_{i}") for i in range(max_id + 1)]

    yaml_lines = [
        f"# Auto-generated by split_datasets.py",
        f"path: {dest.resolve()}",
    ]
    for split_name, split_dir in split_dirs.items():
        yaml_lines.append(f"{split_name}: images/{split_dir.name}"
                          if split_dir.parent == dest / "images"
                          else f"{split_name}: {split_dir.relative_to(dest)}")
    yaml_lines.append("")
    yaml_lines.append(f"nc: {len(names_list)}")
    yaml_lines.append("names:")
    for i, n in enumerate(names_list):
        yaml_lines.append(f"  {i}: {n}")
    (dest / "data.yaml").write_text("\n".join(yaml_lines) + "\n")


def _build_yolo_dir(
    dest: Path,
    job_dir: Path,
    image_ids: list[str],
    image_id_to_path: dict[str, str],
    labels_src: Path,
    hardlink: bool,
) -> tuple[int, int]:
    """Populate <dest>/images/ and <dest>/labels/ for a list of image_ids.

    Returns (n_images_linked, n_labels_copied). Missing originals are
    skipped and logged.
    """
    img_dir = dest / "images"
    lbl_dir = dest / "labels"
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)

    n_img = n_lbl = 0
    missing_img = missing_lbl = 0
    for iid in image_ids:
        img_src = image_id_to_path.get(iid)
        if not img_src:
            missing_img += 1
            continue
        img_src_p = Path(img_src)
        if not img_src_p.exists():
            missing_img += 1
            continue
        _link_or_copy(img_src_p, img_dir / img_src_p.name, hardlink)
        n_img += 1

        lbl_src = labels_src / f"{iid}.txt"
        if lbl_src.exists():
            shutil.copy2(lbl_src, lbl_dir / f"{iid}.txt")
            n_lbl += 1
        else:
            # Empty label file for images with no annotations.
            (lbl_dir / f"{iid}.txt").write_text("")
            missing_lbl += 1
    if missing_img:
        print(f"    warn: {missing_img} image file(s) missing on disk")
    if missing_lbl:
        print(f"    note: {missing_lbl} image(s) had no label file (wrote empty)")
    return n_img, n_lbl


# ---------------------------------------------------------------------------
# fl_pj split
# ---------------------------------------------------------------------------


def build_flpj_split(
    job_dir: Path, seed: int, buffer: float,
    max_test_frames: int, test_frame_share: float,
) -> dict[str, Any]:
    """Return {"test_videos": [...], "test_frames": [...], "train_frames": [...], manifest}."""
    db = job_dir / "labels_deduped" / "pipeline.db"
    if not db.exists():
        raise FileNotFoundError(f"expected deduped pipeline.db at {db}")
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)

    # Build video index
    videos: dict[str, dict[str, Any]] = {}
    image_id_to_path: dict[str, str] = {}
    for iid, path in con.execute("SELECT image_id, image_path FROM image_meta"):
        image_id_to_path[iid] = path

    for iid, data in con.execute("SELECT image_id, data FROM stages WHERE stage='finalize'"):
        m = VIDEO_PAT.match(iid)
        video = m.group(1) if m else iid
        d = json.loads(data)
        v = videos.setdefault(video, {
            "frames": [], "best_margin": {"forklift": -1.0, "palletjack": -1.0},
        })
        v["frames"].append(iid)
        for a in d.get("final_annotations") or []:
            cn = a.get("class_name")
            if cn in ("forklift", "palletjack"):
                bb = a["bbox"]
                margin = min(bb["x1"], bb["y1"], 1 - bb["x2"], 1 - bb["y2"])
                if margin > v["best_margin"][cn]:
                    v["best_margin"][cn] = margin

    n_videos = len(videos)
    n_frames = sum(len(v["frames"]) for v in videos.values())
    target_frames = int(round(n_frames * test_frame_share))

    # Eligibility: cap <=max_test_frames total AND fork-or-pj fully visible
    eligible = [
        (vn, v) for vn, v in videos.items()
        if len(v["frames"]) <= max_test_frames
        and (v["best_margin"]["forklift"] >= buffer
             or v["best_margin"]["palletjack"] >= buffer)
    ]

    # Strategy Z: seeded random shuffle, pick until frame target reached.
    elig_sorted = sorted(eligible, key=lambda x: x[0])  # deterministic pre-shuffle
    rng = random.Random(seed)
    rng.shuffle(elig_sorted)

    picked = []
    acc = 0
    for vn, v in elig_sorted:
        if acc >= target_frames:
            break
        picked.append((vn, v))
        acc += len(v["frames"])

    test_videos = [vn for vn, _ in picked]
    test_video_set = set(test_videos)
    test_frames = [iid for _, v in picked for iid in v["frames"]]
    train_frames = [iid for vn, v in videos.items()
                    if vn not in test_video_set for iid in v["frames"]]

    manifest = {
        "seed": seed,
        "buffer": buffer,
        "max_test_frames": max_test_frames,
        "test_frame_share_target": test_frame_share,
        "eligible_pool_size": len(eligible),
        "test_video_count": len(test_videos),
        "test_frame_count": len(test_frames),
        "train_video_count": n_videos - len(test_video_set),
        "train_frame_count": len(train_frames),
        "test_frame_share_actual": round(len(test_frames) / n_frames, 4),
        "test_videos": sorted(test_videos),
    }

    con.close()
    return {
        "test_videos": test_videos,
        "test_frames": test_frames,
        "train_frames": train_frames,
        "image_id_to_path": image_id_to_path,
        "manifest": manifest,
    }


def _per_class_counts(labels_src: Path, image_ids: list[str]) -> Counter:
    cnt: Counter = Counter()
    for iid in image_ids:
        p = labels_src / f"{iid}.txt"
        if not p.exists():
            continue
        for line in p.read_text().splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                cid = int(line.split(None, 1)[0])
                cnt[cid] += 1
            except ValueError:
                continue
    return cnt


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> int:
    args = _parse_args()
    dest = args.dest.resolve()
    dest.mkdir(parents=True, exist_ok=True)

    # --- LOCO (all train) ---
    loco_job = Path("output/auto_annotation_v4/loco_unannotated_full_sam_filtered_detect")
    loco_labels_src = loco_job / "labels_deduped" / "labels"
    loco_db = loco_job / "labels_deduped" / "pipeline.db"
    print(f"=== LOCO -> loco_train ===")
    con = sqlite3.connect(f"file:{loco_db}?mode=ro", uri=True)
    loco_id_to_path = dict(con.execute("SELECT image_id, image_path FROM image_meta"))
    loco_ids = list(loco_id_to_path.keys())
    con.close()
    loco_dest = dest / "loco_train"
    n_i, n_l = _build_yolo_dir(
        loco_dest, loco_job, loco_ids, loco_id_to_path, loco_labels_src,
        hardlink=not args.no_hardlink,
    )
    _write_classes_and_data_yaml(
        loco_dest, loco_job / "classes.txt",
        {"train": loco_dest / "images", "val": loco_dest / "images"},
    )
    loco_counts = _per_class_counts(loco_labels_src, loco_ids)
    (loco_dest / "split_manifest.json").write_text(json.dumps({
        "kind": "loco_train",
        "n_images": n_i,
        "n_labels": n_l,
        "per_class_box_counts": dict(sorted(loco_counts.items())),
    }, indent=2) + "\n")
    print(f"  images linked: {n_i:,}   labels: {n_l:,}  out: {loco_dest}")

    # --- fl_pj (train + test) ---
    flpj_job = Path("output/auto_annotation_v4/fl_pj_frames_dedup_v1_cls_0_85")
    flpj_labels_src = flpj_job / "labels_deduped" / "labels"
    print(f"\n=== fl_pj -> flpj_train + flpj_test ===")
    split = build_flpj_split(
        flpj_job, seed=args.seed, buffer=args.buffer,
        max_test_frames=args.max_test_frames,
        test_frame_share=args.test_frame_share,
    )

    # Train
    train_dest = dest / "flpj_train"
    n_i, n_l = _build_yolo_dir(
        train_dest, flpj_job, split["train_frames"],
        split["image_id_to_path"], flpj_labels_src,
        hardlink=not args.no_hardlink,
    )
    train_counts = _per_class_counts(flpj_labels_src, split["train_frames"])
    # Test
    test_dest = dest / "flpj_test"
    n_i_t, n_l_t = _build_yolo_dir(
        test_dest, flpj_job, split["test_frames"],
        split["image_id_to_path"], flpj_labels_src,
        hardlink=not args.no_hardlink,
    )
    test_counts = _per_class_counts(flpj_labels_src, split["test_frames"])

    # classes.txt + data.yaml in each split dir
    for dd in (train_dest, test_dest):
        _write_classes_and_data_yaml(
            dd, flpj_job / "classes.txt",
            {"train": train_dest / "images" if dd == train_dest else test_dest / "images"},
        )

    # Combined data.yaml pointing at both splits (optional, at root)
    (dest / "flpj_data.yaml").write_text("\n".join([
        f"# Combined fl_pj train+test YOLO descriptor",
        f"path: {dest}",
        f"train: flpj_train/images",
        f"val:   flpj_test/images",
        f"",
        f"# classes.txt in each split carries the 'id name' mapping",
    ]) + "\n")

    # Manifest + per-class count deltas
    split["manifest"]["train"] = {"n_images": n_i, "n_labels": n_l,
                                   "per_class_box_counts": dict(sorted(train_counts.items()))}
    split["manifest"]["test"]  = {"n_images": n_i_t, "n_labels": n_l_t,
                                   "per_class_box_counts": dict(sorted(test_counts.items()))}
    # Strip the big test_videos list to a side file to keep manifest readable
    test_videos = split["manifest"].pop("test_videos")
    (dest / "flpj_split_manifest.json").write_text(json.dumps(split["manifest"], indent=2) + "\n")
    (dest / "flpj_test_videos.txt").write_text("\n".join(test_videos) + "\n")

    print(f"  train: {n_i:,} images  {n_l:,} labels  ({train_dest})")
    print(f"  test:  {n_i_t:,} images  {n_l_t:,} labels  ({test_dest})")
    print(f"  test video list: {dest / 'flpj_test_videos.txt'}")
    print(f"  split manifest:  {dest / 'flpj_split_manifest.json'}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
